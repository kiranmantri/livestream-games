"""Dump the SOURCE OF TRUTH (the dev PostgreSQL) into a clean, idempotent SQL seed for a fresh cloud database.

    uv run python deploy/make_seed.py                 # writes deploy/seed/phrases_seed.sql

What goes in:   phrases (text, source, enabled, created_at; score = the phrase's PRIOR score) and ingested_videos.
What stays out: game_sessions / users / bingo_cards / bingo_marks (play data) and phrase play statistics:
                dealt/marked are written as 0 and score = prior_score, i.e. the state BEFORE any game was played,
                so test games on the dev machine never leak into production.
The seed is data-only: apply migrations first (python -m app.db), then `psql -f deploy/seed/phrases_seed.sql`.
Every INSERT is `ON CONFLICT DO NOTHING`, so re-applying it never overwrites what the admin edited in the cloud.
"""
from __future__ import annotations

import sys
from datetime import UTC, datetime
from pathlib import Path

import psycopg
from psycopg import sql

from app.config import database_url

OUT = Path("deploy/seed/phrases_seed.sql")
BATCH = 400


def lit(conn: psycopg.Connection, v) -> str:
    return "NULL" if v is None else sql.Literal(v).as_string(conn)


def main(out: Path = OUT) -> int:
    with psycopg.connect(database_url()) as conn:
        applied = [r[0] for r in conn.execute("SELECT name FROM schema_migrations ORDER BY 1")]
        phrases = conn.execute(
            "SELECT text, source, prior_score, enabled, created_at FROM phrases ORDER BY id").fetchall()
        videos = conn.execute(
            "SELECT video_id, title, upload_date, duration_s, width, height, orientation, has_transcript, has_chat, "
            "ingested_at FROM ingested_videos ORDER BY video_id").fetchall()
        polluted = conn.execute("SELECT count(*) FILTER (WHERE dealt > 0 OR marked > 0), "
                                "count(*) FILTER (WHERE abs(score - prior_score) > 1e-9) FROM phrases").fetchone()
        lines = [
            "-- Live Games seed: phrases + ingested_videos (data only). Generated by deploy/make_seed.py",
            f"-- generated {datetime.now(UTC):%Y-%m-%d %H:%M:%SZ} from a database at migration {applied[-1]}",
            (f"-- {len(phrases)} phrases, {len(videos)} videos. Play statistics NOT included"
             f" (dev DB had {polluted[0]} phrases with counters and {polluted[1]} learned scores: reset to the prior)."),
            "-- Requires migrations up to 0005 (python -m app.db). Idempotent: ON CONFLICT DO NOTHING.",
            "BEGIN;", "SET LOCAL client_min_messages = warning;"]
        for i in range(0, len(phrases), BATCH):
            rows = ",\n".join(
                f"({lit(conn, t)},{lit(conn, s)},{float(p)!r},{float(p)!r},{'true' if e else 'false'},{lit(conn, c)})"
                for t, s, p, e, c in phrases[i:i + BATCH])
            lines.append("INSERT INTO phrases (text, source, score, prior_score, enabled, created_at) VALUES\n"
                         f"{rows}\nON CONFLICT (text) DO NOTHING;")
        if videos:
            rows = ",\n".join("(" + ",".join(lit(conn, x) for x in v) + ")" for v in videos)
            lines.append("INSERT INTO ingested_videos (video_id, title, upload_date, duration_s, width, height, "
                         f"orientation, has_transcript, has_chat, ingested_at) VALUES\n{rows}\nON CONFLICT (video_id) DO NOTHING;")
        lines += ["COMMIT;", ""]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"{out}: {len(phrases)} phrases, {len(videos)} videos, {out.stat().st_size / 1024:.0f} KiB "
          f"(dev DB at {applied[-1]}; counters/learned scores reset on {polluted})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
