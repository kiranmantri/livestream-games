"""Build a clean, idempotent SQL seed (phrases only) for a fresh database.

    uv run python -m deploy.make_seed                              # from the DEV database (DATABASE_URL)
    uv run python -m deploy.make_seed --from-dump data/backup      # from CSV dumps of the CLOUD database (source of truth)

Cloud dump (run from the repo root; files are gitignored under data/backup/):
    fly ssh console --app livebingo --container db -C "psql -U livegames -d livegames -h 127.0.0.1 \\
      -c \\"COPY (SELECT * FROM phrases ORDER BY 1) TO STDOUT WITH (FORMAT csv, HEADER, NULL '\\\\N')\\"" \\
      | grep -v '^Connecting' > data/backup/cloud_phrases.csv

What goes in:   phrases (text, source, enabled, created_at; score = prior_score = the phrase's PRIOR score).
                What stays out: game_sessions / users / bingo_cards / bingo_marks and the phrase
                play statistics (dealt/marked are 0, score = prior_score: the state BEFORE any game was played).
The seed is data-only: apply migrations first (python -m app.db). Every INSERT is `ON CONFLICT DO NOTHING`, and the
container entrypoint only applies it when the phrases table is EMPTY.
"""
from __future__ import annotations

import argparse
import csv
import sys
from datetime import UTC, datetime
from pathlib import Path

OUT = Path("deploy/seed/phrases_seed.sql")
BATCH = 400
PHRASE_COLS = ("text", "source", "prior_score", "enabled", "created_at")


def lit(v: object) -> str:
    """SQL literal. Everything is sent as a quoted string and coerced by Postgres to the column type."""
    if v is None:
        return "NULL"
    return "'" + str(v).replace("'", "''") + "'"


def _from_csv(path: Path, cols: tuple[str, ...]) -> list[tuple]:
    with path.open(newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    missing = [c for c in cols if rows and c not in rows[0]]
    if missing:
        raise SystemExit(f"{path}: missing columns {missing}")
    return [tuple(None if r[c] == "\\N" else r[c] for c in cols) for r in rows]


def _from_dev_db() -> tuple[list[tuple], str]:
    import psycopg

    from app.config import database_url
    with psycopg.connect(database_url()) as conn:
        last = conn.execute("SELECT max(name) FROM schema_migrations").fetchone()[0]  # type: ignore[index]
        phrases = conn.execute(f"SELECT {', '.join(PHRASE_COLS)} FROM phrases ORDER BY id").fetchall()
    return phrases, f"dev database at migration {last}"


def build(phrases: list[tuple], origin: str) -> str:
    enabled = sum(1 for p in phrases if str(p[3]).lower() in ("t", "true", "1"))
    lines = [
        "-- Live Games seed: phrases (data only). Generated by deploy/make_seed.py",
        f"-- generated {datetime.now(UTC):%Y-%m-%d %H:%M:%SZ} from: {origin}",
        f"-- {len(phrases)} phrases ({enabled} enabled). Play statistics NOT included.",
        "-- Requires migrations up to 0006 (python -m app.db). Idempotent: ON CONFLICT DO NOTHING.",
        "BEGIN;", "SET LOCAL client_min_messages = warning;"]
    for i in range(0, len(phrases), BATCH):
        rows = ",\n".join(f"({lit(t)},{lit(s)},{lit(p)},{lit(p)},{lit(e)},{lit(c)})"
                          for t, s, p, e, c in phrases[i:i + BATCH])
        lines.append("INSERT INTO phrases (text, source, score, prior_score, enabled, created_at) VALUES\n"
                     f"{rows}\nON CONFLICT (text) DO NOTHING;")
    return "\n".join([*lines, "COMMIT;", ""])


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=(__doc__ or "").split("\n")[0])
    ap.add_argument("--from-dump", type=Path, metavar="DIR",
                    help="read DIR/cloud_phrases.csv (a COPY dump of the cloud database) instead of the dev database")
    ap.add_argument("--out", type=Path, default=OUT)
    args = ap.parse_args(argv)
    if args.from_dump:
        phrases = _from_csv(args.from_dump / "cloud_phrases.csv", PHRASE_COLS)
        origin = f"CSV dumps of the cloud database ({args.from_dump})"
    else:
        phrases, origin = _from_dev_db()
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(build(phrases, origin), encoding="utf-8")
    print(f"{args.out}: {len(phrases)} phrases, {args.out.stat().st_size / 1024:.0f} KiB ({origin})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
